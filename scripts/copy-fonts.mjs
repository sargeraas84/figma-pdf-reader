/**
 * Copy open-licensed (SIL OFL) font TTFs from @expo-google-fonts packages into
 * `public/fonts/` and generate `src/lib/fonts-manifest.json`.
 *
 * Usage: node scripts/copy-fonts.mjs
 */
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const outDir = path.join(root, "public", "fonts");
fs.mkdirSync(outDir, { recursive: true });

// family id → package dir + wanted styles
const FAMILIES = [
  { id: "roboto", pkg: "roboto", label: "Roboto", familyName: "Roboto", italic: true },
  { id: "open-sans", pkg: "open-sans", label: "Open Sans", familyName: "Open Sans", italic: true },
  { id: "lato", pkg: "lato", label: "Lato", familyName: "Lato", italic: true },
  { id: "inter", pkg: "inter", label: "Inter", familyName: "Inter", italic: true },
  { id: "oswald", pkg: "oswald", label: "Oswald", familyName: "Oswald", italic: false },
  { id: "merriweather", pkg: "merriweather", label: "Merriweather", familyName: "Merriweather", italic: true }
];

const stylesWanted = [
  { slot: "regular", dir: "400Regular" },
  { slot: "bold", dir: "700Bold" },
  { slot: "italic", dir: "400Regular_Italic" },
  { slot: "boldItalic", dir: "700Bold_Italic" }
];

const manifest = FAMILIES.map((fam) => {
  const files = {};
  for (const s of stylesWanted) {
    if (s.slot.includes("Italic") && !fam.italic) continue;
    const srcDir = path.join(root, "node_modules", "@expo-google-fonts", fam.pkg, s.dir);
    if (!fs.existsSync(srcDir)) continue;
    const ttf = fs
      .readdirSync(srcDir)
      .find((f) => f.toLowerCase().endsWith(".ttf"));
    if (!ttf) continue;
    const destName = `${fam.familyName.replace(/\s+/g, "")}_${s.slot}.ttf`;
    fs.copyFileSync(path.join(srcDir, ttf), path.join(outDir, destName));
    files[s.slot] = destName;
  }
  return {
    id: fam.id,
    label: fam.label,
    familyName: fam.familyName,
    italicSupported: fam.italic,
    files
  };
});

const tsPath = path.join(root, "src", "lib", "fonts-manifest.ts");
fs.writeFileSync(
  tsPath,
  `// AUTO-GENERATED by scripts/copy-fonts.mjs — do not edit by hand.\n` +
    `// All bundled fonts are licensed under the SIL Open Font License.\n` +
    `export interface FontFiles {\n  regular?: string;\n  bold?: string;\n  italic?: string;\n  boldItalic?: string;\n}\n\n` +
    `export interface EmbeddedFont {\n  id: string;\n  label: string;\n  familyName: string;\n  italicSupported: boolean;\n  files: FontFiles;\n}\n\n` +
    `export const EMBEDDED_FONTS: EmbeddedFont[] = ${JSON.stringify(manifest, null, 2)};\n`
);

fs.writeFileSync(
  path.join(outDir, "manifest.json"),
  JSON.stringify(manifest, null, 2)
);

const total = manifest.reduce((n, f) => n + Object.keys(f.files).length, 0);
console.log(`copied ${total} ttf files, manifest → src/lib/fonts-manifest.ts`);
